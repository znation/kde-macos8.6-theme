"""Tests for the shared generated-file publisher's default write path."""

from __future__ import annotations

import unittest

from support import repo_root  # noqa: F401  (puts the repository root on sys.path)
from support.tmp_dir import make_tmp_dir
from tools.generated_files import write_generated_files


class TestGeneratedFiles(unittest.TestCase):
    def test_default_writer_creates_directory_and_publishes_bytes(self):
        root = make_tmp_dir(self)
        directory = root / "package" / "assets"
        target = directory / "image.bin"

        result = write_generated_files(
            "test-generator", root, directory, [(target, b"generated bytes")]
        )

        self.assertEqual(result, 0)
        self.assertEqual(target.read_bytes(), b"generated bytes")


if __name__ == "__main__":
    unittest.main()
