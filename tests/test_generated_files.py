"""Tests for the shared generated-file publisher's write paths.

The success path, the containment refusal, the directory-creation failure
and a write failure partway through the files each end the run their own way:
status 0 with every pair published, or status 2 with one
``tool: error:`` diagnostic through the shared reporter and any files
before the failed one left written.
"""

from __future__ import annotations

import contextlib
import io
import unittest
from pathlib import Path

from support import repo_root  # noqa: F401  (puts the repository root on sys.path)
from support.tmp_dir import make_tmp_dir
from tools.generated_files import write_generated_files


class TestGeneratedFiles(unittest.TestCase):
    def test_default_writer_creates_directory_and_publishes_bytes(self):
        root = make_tmp_dir(self)
        directory = root / "package" / "assets"
        target = directory / "image.bin"

        result = write_generated_files(
            "test-generator", root, directory, [(target, b"generated bytes")]
        )

        self.assertEqual(result, 0)
        self.assertEqual(target.read_bytes(), b"generated bytes")

    def test_a_symlink_escape_refuses_the_directory_and_writes_nothing(self):
        tmp = make_tmp_dir(self)
        root = tmp / "repo"
        root.mkdir()
        # The escape target sits beside the repository, inside the same
        # per-test temporary directory so it cannot collide with any other
        # test's paths and is cleaned up with it.
        outside = tmp / "escapes"
        outside.mkdir()
        link = root / "package"
        link.symlink_to(outside)
        directory = link / "assets"
        written = []

        stderr = io.StringIO()
        with contextlib.redirect_stderr(stderr):
            result = write_generated_files(
                "test-generator",
                root,
                directory,
                [(directory / "image.bin", b"generated bytes")],
                write=lambda target, data: written.append(target),
            )

        self.assertEqual(result, 2)
        self.assertEqual(written, [])
        self.assertFalse((outside / "assets").exists())
        self.assertEqual(
            stderr.getvalue(),
            f"test-generator: error: {directory} resolves outside {root} "
            "(a symlink escape); refusing to write it\n",
        )

    def test_a_directory_creation_failure_is_reported_with_status_two(self):
        root = make_tmp_dir(self)
        # A regular file where the package directory belongs: mkdir cannot
        # create ``package/assets`` beneath it.
        (root / "package").write_bytes(b"not a directory")
        directory = root / "package" / "assets"
        written = []

        stderr = io.StringIO()
        with contextlib.redirect_stderr(stderr):
            result = write_generated_files(
                "test-generator",
                root,
                directory,
                [(directory / "image.bin", b"generated bytes")],
                write=lambda target, data: written.append(target),
            )

        self.assertEqual(result, 2)
        self.assertEqual(written, [])
        self.assertTrue(stderr.getvalue().startswith(
            f"test-generator: error: cannot create {directory}: "
        ))

    def test_a_write_failure_stops_the_run_and_keeps_earlier_files(self):
        root = make_tmp_dir(self)
        directory = root / "package"
        first = directory / "first.bin"
        second = directory / "second.bin"

        def failing_write(target: Path, data: bytes) -> None:
            if target == second:
                raise OSError("disk full")
            with open(target, "wb") as handle:
                handle.write(data)

        stderr = io.StringIO()
        with contextlib.redirect_stderr(stderr):
            result = write_generated_files(
                "test-generator",
                root,
                directory,
                [(first, b"first bytes"), (second, b"second bytes")],
                write=failing_write,
            )

        self.assertEqual(result, 2)
        # The pair before the failure stays published whole; the failed one
        # leaves no partial file behind.
        self.assertEqual(first.read_bytes(), b"first bytes")
        self.assertFalse(second.exists())
        self.assertEqual(
            stderr.getvalue(),
            f"test-generator: error: cannot write {second}: disk full\n",
        )


if __name__ == "__main__":
    unittest.main()
